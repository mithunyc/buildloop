#!/usr/bin/env node

/**
 * init.mjs — write a working .buildloop.yml from what the repo already has.
 *
 * Founders should not hand-edit YAML placeholders. This reads package.json
 * scripts (or Cargo/Go/Python markers), fills in real gate commands, marks
 * anything it cannot find as "n/a", and says plainly what is still missing.
 * It also adds Buildloop's evidence folders to .gitignore.
 *
 * Never overwrites an existing .buildloop.yml unless --force is given.
 * Exit codes: 0 = written (or dry run), 1 = refused/error, 2 = invalid arguments.
 *
 * Usage:
 *   node scripts/init.mjs [--cwd <path>] [--force] [--dry-run]
 */

import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const NPM_DEFAULT_TEST = /no test specified/;
const IGNORE_LINES = ['.buildloop/', '.buildloop-runs/'];

function flag(args, name) {
  const idx = args.indexOf(name);
  return idx === -1 || idx + 1 >= args.length ? null : args[idx + 1];
}

function nodeManager(cwd) {
  if (existsSync(join(cwd, 'pnpm-lock.yaml'))) return 'pnpm';
  if (existsSync(join(cwd, 'yarn.lock'))) return 'yarn';
  if (existsSync(join(cwd, 'bun.lockb')) || existsSync(join(cwd, 'bun.lock'))) return 'bun';
  return 'npm';
}

/** Returns { stack, commands: {lint,typecheck,test,build}, notes: string[] }. */
export function inferGates(cwd) {
  const notes = [];
  const pkgPath = join(cwd, 'package.json');

  if (existsSync(pkgPath)) {
    let scripts = {};
    try {
      scripts = JSON.parse(readFileSync(pkgPath, 'utf8')).scripts ?? {};
    } catch {
      notes.push('package.json could not be parsed; gates set to n/a.');
    }
    const pm = nodeManager(cwd);
    const run = (name) => `${pm} run ${name}`;
    const pick = (...names) => names.find((n) => typeof scripts[n] === 'string');
    const typecheckScript = pick('typecheck', 'type-check', 'tsc');
    const testScript = pick('test') && !NPM_DEFAULT_TEST.test(scripts.test) ? 'test' : pick('test:unit', 'vitest', 'jest');
    const commands = {
      lint: pick('lint') ? run('lint') : 'n/a',
      typecheck: typecheckScript ? run(typecheckScript)
        : existsSync(join(cwd, 'tsconfig.json')) ? 'npx tsc --noEmit' : 'n/a',
      test: testScript ? run(testScript) : 'n/a',
      build: pick('build') ? run('build') : 'n/a',
    };
    return { stack: `node (${pm})`, commands, notes };
  }
  if (existsSync(join(cwd, 'Cargo.toml'))) {
    return { stack: 'rust', commands: { lint: 'cargo clippy -- -D warnings', typecheck: 'n/a', test: 'cargo test', build: 'cargo build' }, notes };
  }
  if (existsSync(join(cwd, 'go.mod'))) {
    return { stack: 'go', commands: { lint: 'go vet ./...', typecheck: 'n/a', test: 'go test ./...', build: 'go build ./...' }, notes };
  }
  if (['pyproject.toml', 'setup.py', 'requirements.txt'].some((f) => existsSync(join(cwd, f)))) {
    notes.push('Python detected: assumed pytest. Change the test command if you use something else.');
    return { stack: 'python', commands: { lint: 'n/a', typecheck: 'n/a', test: 'python -m pytest', build: 'n/a' }, notes };
  }
  notes.push('No known project type found; every gate is n/a.');
  return { stack: 'unknown', commands: { lint: 'n/a', typecheck: 'n/a', test: 'n/a', build: 'n/a' }, notes };
}

export function renderConfig({ stack, commands }) {
  const quote = (v) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  return [
    `# Generated by buildloop init for a ${stack} project. Review the commands once.`,
    '# A gate set to "n/a" is skipped; verify refuses DONE when every gate is n/a.',
    'adoption_mode: brownfield',
    'risk_level: medium',
    '',
    'commands:',
    ...['lint', 'typecheck', 'test', 'build'].map((k) => `  ${k}: ${quote(commands[k])}`),
    '',
    'protected_paths:',
    '  - ".env*"',
    '  - "**/*.key"',
    '  - "**/*.pem"',
    '  - "**/*.p12"',
    '  - ".github/workflows/**"',
    '',
  ].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const cwd = resolve(flag(args, '--cwd') ?? process.cwd());
  const target = join(cwd, '.buildloop.yml');
  const dryRun = args.includes('--dry-run');

  if (existsSync(target) && !args.includes('--force')) {
    console.error(`init: ${target} already exists. Re-run with --force to replace it.`);
    process.exit(1);
  }

  const gates = inferGates(cwd);
  const config = renderConfig(gates);
  if (dryRun) {
    console.log(config);
  } else {
    writeFileSync(target, config, 'utf8');
    const gitignore = join(cwd, '.gitignore');
    const existing = existsSync(gitignore) ? readFileSync(gitignore, 'utf8') : '';
    const missing = IGNORE_LINES.filter((line) => !existing.split(/\r?\n/).includes(line));
    if (missing.length) {
      appendFileSync(gitignore, `${existing && !existing.endsWith('\n') ? '\n' : ''}${missing.join('\n')}\n`, 'utf8');
    }
  }

  const ran = Object.entries(gates.commands).filter(([, v]) => v !== 'n/a');
  console.log(`buildloop init - ${dryRun ? 'would write' : 'wrote'} .buildloop.yml (${gates.stack})`);
  for (const [name, command] of Object.entries(gates.commands)) console.log(`  ${name.padEnd(9)} ${command}`);
  for (const note of gates.notes) console.log(`  note: ${note}`);
  if (gates.commands.test === 'n/a') {
    console.log('\n  WARNING: no test command found. Nothing proves the code works until you add one;');
    console.log('  ask your agent to add a test script before building features.');
  }
  console.log(`\n  ${ran.length}/4 gates active. Next: node <buildloop>/scripts/gate-runner.mjs`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
